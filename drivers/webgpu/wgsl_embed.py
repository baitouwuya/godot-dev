"""Emit typed C++ data from verified native compiler output."""

from collections import defaultdict
import json


STAGES = ("vertex", "fragment", "compute")


def key(value, role="texture"):
    return "{%s, %s, %s, Role::%s}" % (value.get("set", 0), value["binding"], value.get("element", 0),
                                      value.get("role", role).upper())


def key_list(values, role="texture"):
    return "{" + ",".join(key(value, role) for value in values) + "}"


def embedded_header(jobs, results, compiler):
    out = ["// Generated by wgsl_precompile.py. Do not edit.", "namespace godot::webgpu::embedded {",
           "static_assert(SHADER_PLAN_VERSION == 1);", f'inline constexpr char compiler[] = "{compiler}";',
           "using Options = CompileOptions (*)();", "using Plan = ShaderPlan (*)();",
           "struct Entry { std::array<const char *, SHADER_STAGE_COUNT> sha256; Options options; Plan plan; };"]
    entries = []
    for i, (job, result) in enumerate(zip(jobs, results, strict=True)):
        options = defaultdict(list, job.get("options", {}))
        out += [f"inline CompileOptions options_{i}() {{", "CompileOptions options;"]
        for prop in ("uniform_memory_fences", "texture_barrier", "promote_narrow_storage", "non_uniform_derivatives", "flip_vertex_y"):
            if prop in options:
                out.append(f"options.{prop} = {str(options[prop]).lower()};")
        if "subgroup_lowering" in options:
            out.append(f'options.subgroup_lowering = SubgroupLowering::{options["subgroup_lowering"].upper()};')
        for item in options["specialization"]:
            out.append(f'options.specialization[{item["id"]}u] = {item["bits"]}u;')
        for prop in ("raw_depth", "unfilterable_float"):
            if prop in options:
                out.append(f"options.{prop} = {key_list(options[prop])};")
        for item in options["storage_formats"]:
            out.append(f'options.storage_formats[{key(item, "storage_texture")}] = {item["format"]}u;')
        for item in options["immutable_samplers"]:
            out.append(f'options.immutable_samplers[{key(item, "sampler")}] = {item["equivalence"]}u;')
        out += ["return options;", "}", f"inline ShaderPlan plan_{i}() {{", "ShaderPlan plan;"]
        plan = result["plan"]
        for binding in plan["bindings"]:
            f = binding["format"]
            fmt = (f'{{{f["logical"]}, {f["physical"]}, {f["dimension"]}, {int(f["arrayed"])}, {int(f["multisampled"])}, '
                   f'{int(f["depth_only_view"])}, ImageAccess({f["access"]}), SampleType({f["sample_type"]}), '
                   f'FormatConversion({f["conversion"]}), {f["bits"]}, {f["channels"]}, {int(f["atomic_buffer"])}}}')
            out.append(f'plan.bindings.push_back({{{key(binding)}, {binding["group"]}, {binding["slot"]}, {binding["stages"]}, '
                       f'{int(binding["read_only"])}, SamplerType({binding["sampler_type"]}), {fmt}, {key_list(binding["aliases"])}}});')
        pc = plan["push_constant"]
        out.append(f'plan.push_constant = {{{pc["size"]}, {pc["stages"]}, {pc["group"]}, {pc["slot"]}}};')
        out.append(f'plan.uses_texture_barrier = {int(plan["uses_texture_barrier"])};')
        hashes = []
        for index, stage in enumerate(STAGES):
            counts = plan["limits"][stage]
            out.append(f'plan.limits[{index}] = {{{", ".join(str(counts[c]) for c in "TSBIU")}}};')
            meta = result["stages"].get(stage)
            if not meta:
                hashes.append('""')
                continue
            hashes.append(json.dumps(meta["sha256"]))
            wgsl = meta["wgsl"]
            delimiter = "wgsl"
            while f'){delimiter}"' in wgsl:
                delimiter += "_"
            out.append(f'plan.stages.push_back({{Stage::{stage.upper()}, {json.dumps(meta["entry_point"])}, R"{delimiter}({wgsl}){delimiter}"}});')
        out += ["return plan;", "}"]
        entries.append("{{" + ", ".join(hashes) + f"}}, options_{i}, plan_{i}}},")
    return "\n".join(out + ["inline constexpr Entry entries[] = {", *entries, "};", "}", ""])
